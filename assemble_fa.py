"""Assemble the Persian edition and check it against the English edition.

Output: enterprise-ai-strategy-and-implementation-handbook-fa.md (RTL-wrapped Markdown)
Checks, per section (front matter, chapters 1-10, appendices B-D):
  - identical multiset of workspace/FINOS/external citations
  - identical number of Mermaid diagrams (and diagram types) and Markdown tables
  - 10 chapters, 10 chapter cards, 15 tools (C.0-C.14)
"""
from pathlib import Path
import json, re, collections, sys

P = Path(__file__).parent
FA = P / 'fa'
R = json.loads((P / 'source-register.json').read_text(encoding='utf-8'))


def read(p):
    return Path(p).read_text(encoding='utf-8').strip()


def cell(s):
    return str(s).replace('|', '/').replace('\n', ' ').strip()


# ---------------------------------------------------------------- Persian source key (Appendix A)
en_key = read(P / 'appendix-a-source-key.md')  # generated by assemble_and_verify.py
rows = [l for l in en_key.splitlines() if l.startswith('| ') and not l.startswith('| ID ') and not l.startswith('| Citation ')]
d_rows = [l for l in rows if re.match(r'\| D\d{2} ', l)]
img_rows = [l for l in rows if re.match(r'\| (A\d{2}|F1\d) ', l)]
finos_rows = [l for l in rows if l.startswith('| FINOS ')]
key = ['# پیوست الف — کلید منابع', '',
       'این پیوست معنای شناسه‌های کوتاهی را که در ارجاع‌های متن آمده توضیح می‌دهد. عنوان منابع به زبان اصلی آمده است. به نوع هر منبع توجه کنید: روایت خود شرکت‌ها، تحلیل مشاوران، فهرست‌هایی که جامعهٔ متخصصان تهیه کرده و گزارش نهادهای ناظر، وزن یکسانی ندارند (برچسب‌های شواهد در بخش [شیوهٔ استفاده از این راهنما](#how-to-use) را ببینید). نام کامل پرونده‌ها، میزان بررسی هر کدام، نشانی‌هایی که بررسی شده، محدودیت‌ها و اثرانگشت SHA-256 هر ۱۹۷ پرونده در بخش ۱ فایل همراه انگلیسی، [handbook-evidence-companion.md](handbook-evidence-companion.md)، آمده است. منابع بیرونی (شناسه‌های E01 تا E12) در [پیوست د.۲](#appendix-d) معرفی شده‌اند.', '',
       '## الف.۱ اسناد اصلی', '', '| شناسه | عنوان | سازمان / گوینده؛ تاریخ | نوع منبع |', '|---|---|---|---|'] + d_rows + [
       '', '## الف.۲ تصاویر و نمودارهای ارجاع‌شده', '', '| شناسه | محتوا | منبع مادر / رابطه |', '|---|---|---|'] + img_rows + [
       '', '## الف.۳ پرونده‌های ارجاع‌شده از چارچوب حاکمیت هوش مصنوعی FINOS', '',
       'برگرفته از نسخهٔ مخزن در `ai-governance-framework-main/`. «Draft» و «Approved-Specification» وضعیت‌های درون پروژه‌اند، نه وضعیت حقوقی.', '',
       '| ارجاع | عنوان | شناسهٔ فهرست | وضعیت در پروژه |', '|---|---|---|---|'] + finos_rows
(FA / 'appendix-a-source-key-fa.md').write_text('\n'.join(key) + '\n', encoding='utf-8')

# ---------------------------------------------------------------- assemble
parts = [('00-front.md', None), ('01-ch1-3.md', None), ('02-ch4-5.md', None), ('03-ch6-7.md', None), ('04-ch8-10.md', None),
         ('appendix-a-source-key-fa.md', 'appendix-a'), ('05-appendix-b.md', 'appendix-b'),
         ('06-appendix-c.md', 'appendix-c'), ('07-appendix-d.md', 'appendix-d')]
body = '\n\n---\n\n'.join(((f'<a id="{a}"></a>\n\n' if a else '') + read(FA / f)) for f, a in parts)
body = body.replace('](../handbook-evidence-companion.md)', '](handbook-evidence-companion.md)')
manuscript = '<div dir="rtl" lang="fa">\n\n' + body + '\n\n</div>\n'
dest = P / 'enterprise-ai-strategy-and-implementation-handbook-fa.md'
dest.write_text(manuscript, encoding='utf-8')

# ---------------------------------------------------------------- fidelity checks against English
en = read(P / 'enterprise-ai-strategy-and-implementation-handbook.md')


def split_en(t):
    s = {}
    i1 = t.index('## 1. Set the mandate')
    s['front'] = t[:i1]
    heads = [m.start() for m in re.finditer(r'^## \d+\. ', t, re.M)]
    a = t.index('<a id="appendix-a">')
    for n, h in enumerate(heads, 1):
        s[f'ch{n}'] = t[h:(heads[n] if n < len(heads) else a)]
    b, c, d = (t.index(f'<a id="appendix-{x}">') for x in 'bcd')
    s['appB'], s['appC'], s['appD'] = t[b:c], t[c:d], t[d:]
    return s


def split_fa(t):
    s = {}
    marks = ['<a id="ch%d">' % n for n in range(1, 11)]
    pos = [t.index(m) for m in marks]
    a = t.index('<a id="appendix-a">')
    s['front'] = t[:pos[0]]
    for n in range(10):
        s[f'ch{n+1}'] = t[pos[n]:(pos[n+1] if n < 9 else a)]
    b, c, d = (t.index(f'<a id="appendix-{x}">') for x in 'bcd')
    s['appB'], s['appC'], s['appD'] = t[b:c], t[c:d], t[d:]
    return s


CIT = re.compile(r'\b(D\d{2} (?:pp?\.|ll?\.) \d+(?:[–-]\d+)?(?:,\s*\d+(?:[–-]\d+)?)*|(?:mi|ri|uc)-\d+|E\d{2}|F1\d|A\d{2})\b')


def cits(x):
    return collections.Counter(m.group(1).replace(' ', '') for m in CIT.finditer(x))


def tables(x):
    return len(re.findall(r'^\|[-|]+\|$', x, re.M))


def diagrams(x):
    return collections.Counter(re.findall(r'```mermaid\n(\w[\w-]*)', x))


E, F = split_en(en), split_fa(manuscript)
problems = []
for k in E:
    ce, cf = cits(E[k]), cits(F[k])
    if ce != cf:
        problems.append((k, 'citations', dict(ce - cf), dict(cf - ce)))
    if diagrams(E[k]) != diagrams(F[k]):
        problems.append((k, 'diagrams', dict(diagrams(E[k])), dict(diagrams(F[k]))))
    if tables(E[k]) != tables(F[k]):
        problems.append((k, 'tables', tables(E[k]), tables(F[k])))

chap = re.findall(r'^## ([۰-۹]+)\. ', manuscript, re.M)
FA_DIGITS = str.maketrans('۰۱۲۳۴۵۶۷۸۹', '0123456789')
tools = [d.translate(FA_DIGITS) for d in re.findall(r'^## ج\.([۰-۹]+) ', manuscript, re.M)]
cards = manuscript.count('| کارت فصل | |')
assert len(chap) == 10, chap
assert tools == [str(i) for i in range(15)], tools
assert cards == 10, cards
assert manuscript.count('```') % 2 == 0 and '�' not in manuscript

report = {'status': 'PASS' if not problems else 'DIFFERENCES', 'chapters': len(chap), 'chapter_cards': cards, 'tools': len(tools),
          'mermaid_diagrams': len(re.findall(r'```mermaid', manuscript)), 'citations_fa': sum(cits(manuscript).values()),
          'problems': problems, 'output': dest.name, 'words': len(manuscript.split())}
print(json.dumps(report, ensure_ascii=False, indent=1))
sys.exit(0 if not problems else 1)
